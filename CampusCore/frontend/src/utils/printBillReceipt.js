import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';

const formatDate = (value) => {
  if (!value) return '';
  const [year, month, day] = value.split('-');
  return year && month && day ? `${day}/${month}/${year}` : value;
};

const formatAmount = (value) => `Rs. ${Number(value || 0).toLocaleString('en-IN', {
  minimumFractionDigits: 2,
  maximumFractionDigits: 2,
})}`;

async function createBillReceiptPdf(receipt, address) {
  const document = await PDFDocument.create();
  const page = document.addPage([595.56, 842.04]);
  const regular = await document.embedFont(StandardFonts.Helvetica);
  const bold = await document.embedFont(StandardFonts.HelveticaBold);
  const { width } = page.getSize();
  const margin = 48;
  const contentWidth = width - margin * 2;
  const centerText = (text, y, size, font, color) => {
    const textWidth = font.widthOfTextAtSize(text, size);
    page.drawText(text, {
      x: (width - textWidth) / 2,
      y,
      size,
      font,
      color,
    });
  };
  const navy = rgb(0.12, 0.19, 0.29);
  const blue = rgb(0.1, 0.27, 0.75);
  const red = rgb(0.75, 0.12, 0.15);
  const lightGray = rgb(0.95, 0.96, 0.97);
  const logoResponse = await fetch('/logo_sts.png');
  if (!logoResponse.ok) {
    throw new Error('The STS logo could not be loaded.');
  }
  const logo = await document.embedPng(await logoResponse.arrayBuffer());
  const logoScale = Math.min(100 / logo.width, 70 / logo.height);

  page.drawLine({
    start: { x: margin, y: 790 },
    end: { x: width - margin, y: 790 },
    thickness: 1.2,
    color: navy,
  });
  page.drawImage(logo, {
    x: margin,
    y: 741,
    width: logo.width * logoScale,
    height: logo.height * logoScale,
  });
  centerText('Scope Tech Software Solution', 754, 18, bold, navy);
  centerText('E-Receipt', 729, 13, bold, red);
  address.forEach((line, index) => {
    centerText(line, 702 - index * 13, 7.5, bold, blue);
  });
  centerText('Contact Number: 6383406578 | 9600936470', 663, 8.5, bold, blue);
  centerText('Email: scopetechsoftwaresolution@gmail.com', 637, 8.5, bold, blue);

  const rows = [
    ['Receipt Number', receipt.receipt_number],
    ['Receipt Date', formatDate(receipt.receipt_date)],
    ['Student ID', `STU-${receipt.student_id}`],
    ['Student Name', receipt.student_name],
    ['Email', receipt.student_email],
    ['Course Coordinator', receipt.course_coordinator],
    ['Course Title', receipt.course_title],
    ['Course Fee', formatAmount(receipt.course_fee)],
    ['Payment Type', receipt.payment_type],
    ['Mode of Payment', receipt.mode_of_payment],
    ['Received Amount', formatAmount(receipt.received_amount)],
    ['Receipt Generated By', receipt.receipt_generated_by],
    ['Course Duration', receipt.course_duration],
    ['Next Installment Date', formatDate(receipt.next_installment_date) || 'Not applicable'],
    ['Balance Fee', formatAmount(receipt.balance_fee)],
  ];
  const tableX = margin;
  const tableTop = 620;
  const rowHeight = 22;
  const labelWidth = 165;
  const tableBottom = tableTop - rows.length * rowHeight;

  page.drawRectangle({
    x: tableX,
    y: tableBottom,
    width: contentWidth,
    height: rows.length * rowHeight,
    borderColor: navy,
    borderWidth: 0.7,
  });
  rows.forEach((row, rowIndex) => {
    const rowTop = tableTop - rowIndex * rowHeight;
    const rowBottom = rowTop - rowHeight;
    if (rowIndex % 2 === 0) {
      page.drawRectangle({
        x: tableX,
        y: rowBottom,
        width: contentWidth,
        height: rowHeight,
        color: lightGray,
      });
    }
    page.drawLine({
      start: { x: tableX, y: rowBottom },
      end: { x: width - margin, y: rowBottom },
      thickness: 0.6,
      color: navy,
    });
    page.drawText(`${row[0]}:`, {
      x: tableX + 10,
      y: rowTop - 14,
      size: 8.5,
      font: bold,
      color: navy,
    });
    const value = String(row[1] || '—');
    let valueSize = 8.5;
    while (valueSize > 6 && regular.widthOfTextAtSize(value, valueSize) > contentWidth - labelWidth - 20) {
      valueSize -= 0.25;
    }
    page.drawText(value, {
      x: tableX + labelWidth,
      y: rowTop - 14,
      size: valueSize,
      font: regular,
      color: navy,
    });
  });
  page.drawRectangle({
    x: tableX,
    y: tableBottom,
    width: contentWidth,
    height: rows.length * rowHeight,
    borderColor: navy,
    borderWidth: 0.7,
  });
  page.drawLine({
    start: { x: tableX + labelWidth - 5, y: tableTop },
    end: { x: tableX + labelWidth - 5, y: tableBottom },
    thickness: 0.6,
    color: navy,
  });
  centerText(`Receipt Details email to (${receipt.student_email || 'Receiver Email'})`, tableBottom - 30, 9, regular, navy);
  centerText('This is the Computer Generated Bill, Hence Signature Not Required', tableBottom - 56, 9, regular, navy);

  return document.save();
}

export function createArapalayamBillPdf(receipt) {
  return createBillReceiptPdf(receipt, [
    'Address: 16/1 Kalki Bhavanam First Floor, Visuvasapuri 4th Street,',
    'Arappalayam, Madurai 625016',
  ]);
}

export function createTheppakulamBillPdf(receipt) {
  return createBillReceiptPdf(receipt, [
    'Address: Sree Adhithya Steels & Cements, 4/275, New Ramnad Rd,',
    'Near to Standard Fire Works, Madurai, Iravadanallur, Tamil Nadu 625009',
  ]);
}

const createBillPdfByFormat = (receipt, format) => (
  format === 'arapalayam'
    ? createArapalayamBillPdf(receipt)
    : createTheppakulamBillPdf(receipt)
);

export function pdfBytesToDataUri(pdfBytes) {
  const chunks = [];
  for (let offset = 0; offset < pdfBytes.length; offset += 0x8000) {
    chunks.push(String.fromCharCode(...pdfBytes.subarray(offset, offset + 0x8000)));
  }
  return `data:application/pdf;base64,${btoa(chunks.join(''))}`;
}

export async function printBillReceipt(receipt, format) {
  const printWindow = window.open('', '_blank');
  if (!printWindow) {
    throw new Error('The receipt window was blocked. Allow pop-ups and try again.');
  }

  try {
    const pdfBytes = await createBillPdfByFormat(receipt, format);
    const url = URL.createObjectURL(new Blob([pdfBytes], { type: 'application/pdf' }));
    printWindow.location.href = url;
    window.setTimeout(() => URL.revokeObjectURL(url), 60_000);
  } catch (error) {
    printWindow.close();
    throw error;
  }
}

export async function downloadBillReceiptPdf(receipt, format) {
  const pdfBytes = await createBillPdfByFormat(receipt, format);
  const blob = new Blob([pdfBytes], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  const safeReceiptNumber = String(receipt.receipt_number).replace(/[^a-z0-9_-]/gi, '_');
  link.href = url;
  const templateName = format === 'arapalayam' ? 'Arapalayam_Bill' : 'Theppakulam_Bill';
  link.download = `bill_${safeReceiptNumber}_${templateName}.pdf`;
  document.body.appendChild(link);
  link.click();
  link.remove();
  window.setTimeout(() => URL.revokeObjectURL(url), 1000);
  return pdfBytes;
}
